#include <stdio.h>
#include <math.h>

int main(void) {
    double X, Y, A, B;

    X = sqrt(16);
    Y = pow(5, 3);
    A = sin(90);
    B = cos(180);

    printf("X = sqrt(16) = %f\n", X);
    printf("Y = pow(5,3) = %f\n", Y);
    printf("A = sin(90)  = %f\n", A);
    printf("B = cos(180) = %f\n", B);

    return 0;
}
